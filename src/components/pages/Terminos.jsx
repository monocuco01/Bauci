function Texto({ children }) {
  if (!children.includes(EMAIL)) return children
  const [antes, despues] = children.split(EMAIL)
  return (
    <>
      {antes}
      <a href={`mailto:${EMAIL}`} className="font-bold text-[color:var(--accent)] underline underline-offset-4">
        {EMAIL}
      </a>
      {despues}
    </>
  )
}

function Bloque({ b }) {
  if (typeof b === 'string') {
    return <p className="m-0 mb-4"><Texto>{b}</Texto></p>
  }
  if (b.sub) {
    return <h3 className="mb-3 mt-8 font-display text-[1.7rem] font-bold leading-none">{b.sub}</h3>
  }
  return (
    <ul className="m-0 mb-4 grid list-disc gap-2.5 pl-6 marker:text-[color:var(--accent)]">
      {b.lista.map((li) => (
        <li key={li}><Texto>{li}</Texto></li>
      ))}
    </ul>
  )
}

function Indice() {
  return (
    <ol className="m-0 list-none p-0">
      {secciones.map((s) => (
        <li key={s.id}>
          <a
            href={`#${s.id}`}
            className="block py-1.5 text-[.95rem] leading-snug text-[color:var(--ink)] no-underline hover:text-[color:var(--accent)]"
          >
            {s.n ? `${s.n}. ` : ''}{s.titulo}
          </a>
        </li>
      ))}
    </ol>
  )
}

